# Regenerates src/lib/klein-agreements.ts from the Klein review drafts (strips the review banner).
import re,json,sys
D=sys.argv[1] if len(sys.argv)>1 else '/home/box/shared/summers-vacations/properties/klein/contracts-drafts-2026-11-04/'
def parse(fn):
    lines=open(D+fn).read().split('\n')
    assert lines[0].startswith('**DRAFT FOR REVIEW'); lines=lines[1:]
    title=None; secs=[]; cur=None; buf=[]
    def flush():
        if cur is not None: secs.append({'heading':cur,'body':re.sub(r'\n{3,}','\n\n','\n'.join(buf).strip()).replace('**','')})
    for l in lines:
        if l.startswith('# '): title=l[2:].strip(); continue
        if l.startswith('## '): flush(); cur=l[3:].strip(); buf=[]; continue
        if l.startswith('|'):
            c=[x.strip() for x in l.strip('|').split('|')]
            if set(''.join(c))<=set('-: ') or c==['Item','Detail']: continue
            buf.append(f'{c[0]}: {c[1]}'); continue
        buf.append(l)
    flush()
    assert secs[-1]['heading']=='Signatures'
    secs[-1]['body']="""IN WITNESS WHEREOF, the Parties have executed this Agreement as of the Start Date.

SUBSCRIBER: MidwestAF Properties LLC

By (typed signature): [SIGNATURE_NAME]  Printed name: Phil Klein, Owner/Member  Date: [SIGNATURE_DATE]

By (typed signature): [CO_SIGNATURE_NAME]  Printed name: Sydney Klein, Owner/Member  Date: [CO_SIGNATURE_DATE]

HOST: Summers Vacations LLC

By: Brian Summers, Authorized Person
(Host countersigns after receipt.)"""
    return title,secs
out=['/** Klein (MidwestAF Properties LLC) co-hosting agreements, Nov 4, 2026. Generated by scripts/gen-klein-agreements.py; open blanks kept as written. */','export type AgreementSection = { heading?: string; body: string };','']
for var,fn in [('ADVENTURE_ESCAPE','klein-adventure-escape-cohost-DRAFT-2026-11-04.md'),('SILVER_DOLLAR_SUITE','klein-silver-dollar-suite-cohost-DRAFT-2026-11-04.md')]:
    title,secs=parse(fn)
    out.append(f'export const KLEIN_{var}_TITLE = {json.dumps(title)};')
    out.append(f'export const KLEIN_{var}_SECTIONS: AgreementSection[] = {json.dumps(secs,indent=2,ensure_ascii=False)};\n')
open('src/lib/klein-agreements.ts','w').write('\n'.join(out))
